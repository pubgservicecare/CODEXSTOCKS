//! CODE X STOCKS desktop shell.
//!
//! The Rust side is deliberately small: it owns ONE SQLite connection (so the
//! TypeScript layer's BEGIN/COMMIT calls form real transactions), stores image
//! files in the app-data folder, and reads/writes backup files the owner picked.
//! All business logic, validation and encryption run in the shared TypeScript code.
//! No cloud database credentials or API secrets exist in this binary.

use rusqlite::{types::Value as SqlValue, types::ValueRef, Connection};
use serde_json::{Map, Number, Value};
use std::fs;
use std::path::PathBuf;
use std::sync::Mutex;
use tauri::{ipc::Request, ipc::Response, Manager, State};

struct Db(Mutex<Connection>);
struct Dirs {
    media: PathBuf,
}

fn to_sql(v: &Value) -> SqlValue {
    match v {
        Value::Null => SqlValue::Null,
        Value::Bool(b) => SqlValue::Integer(*b as i64),
        Value::Number(n) => match n.as_i64() {
            Some(i) => SqlValue::Integer(i),
            None => SqlValue::Real(n.as_f64().unwrap_or(0.0)),
        },
        Value::String(s) => SqlValue::Text(s.clone()),
        other => SqlValue::Text(other.to_string()),
    }
}

fn from_sql(v: ValueRef) -> Value {
    match v {
        ValueRef::Null => Value::Null,
        ValueRef::Integer(i) => Value::Number(i.into()),
        ValueRef::Real(f) => Number::from_f64(f).map(Value::Number).unwrap_or(Value::Null),
        ValueRef::Text(t) => Value::String(String::from_utf8_lossy(t).into_owned()),
        ValueRef::Blob(b) => Value::String(String::from_utf8_lossy(b).into_owned()),
    }
}

#[derive(serde::Serialize)]
struct ExecResult {
    changes: usize,
}

#[tauri::command]
async fn db_execute(db: State<'_, Db>, sql: String, params: Vec<Value>) -> Result<ExecResult, String> {
    let conn = db.0.lock().map_err(|_| "database lock poisoned".to_string())?;
    let p: Vec<SqlValue> = params.iter().map(to_sql).collect();
    let mut stmt = conn.prepare_cached(&sql).map_err(|e| e.to_string())?;
    let changes = stmt
        .execute(rusqlite::params_from_iter(p.iter()))
        .map_err(|e| e.to_string())?;
    Ok(ExecResult { changes })
}

#[tauri::command]
async fn db_select(
    db: State<'_, Db>,
    sql: String,
    params: Vec<Value>,
) -> Result<Vec<Map<String, Value>>, String> {
    let conn = db.0.lock().map_err(|_| "database lock poisoned".to_string())?;
    let p: Vec<SqlValue> = params.iter().map(to_sql).collect();
    let mut stmt = conn.prepare_cached(&sql).map_err(|e| e.to_string())?;
    let names: Vec<String> = stmt.column_names().iter().map(|s| s.to_string()).collect();
    let mut rows = stmt
        .query(rusqlite::params_from_iter(p.iter()))
        .map_err(|e| e.to_string())?;
    let mut out = Vec::new();
    while let Some(row) = rows.next().map_err(|e| e.to_string())? {
        let mut m = Map::new();
        for (i, n) in names.iter().enumerate() {
            m.insert(n.clone(), from_sql(row.get_ref(i).map_err(|e| e.to_string())?));
        }
        out.push(m);
    }
    Ok(out)
}

/// Only names generated by the app (uuid + image extension) are accepted: no path traversal.
fn media_path(dirs: &Dirs, name: &str) -> Result<PathBuf, String> {
    let ext_ok = name.ends_with(".jpg") || name.ends_with(".png") || name.ends_with(".webp");
    let chars_ok = name
        .chars()
        .all(|c| c.is_ascii_digit() || ('a'..='z').contains(&c) || c == '-' || c == '.');
    if name.len() > 64 || !ext_ok || !chars_ok || name.contains("..") {
        return Err("invalid media file name".into());
    }
    Ok(dirs.media.join(name))
}

#[tauri::command]
async fn media_write(dirs: State<'_, Dirs>, request: Request<'_>) -> Result<(), String> {
    let name = request
        .headers()
        .get("x-name")
        .and_then(|v| v.to_str().ok())
        .ok_or("missing name")?
        .to_string();
    let path = media_path(&dirs, &name)?;
    let tauri::ipc::InvokeBody::Raw(data) = request.body() else {
        return Err("expected raw bytes".into());
    };
    if data.len() > 10 * 1024 * 1024 {
        return Err("file too large".into());
    }
    let tmp = path.with_extension("part");
    fs::write(&tmp, data).map_err(|e| e.to_string())?;
    fs::rename(&tmp, &path).map_err(|e| e.to_string())?;
    Ok(())
}

#[tauri::command]
async fn media_read(dirs: State<'_, Dirs>, name: String) -> Result<Response, String> {
    let path = media_path(&dirs, &name)?;
    let data = fs::read(path).map_err(|e| e.to_string())?;
    Ok(Response::new(data))
}

#[tauri::command]
async fn media_exists(dirs: State<'_, Dirs>, name: String) -> Result<bool, String> {
    Ok(media_path(&dirs, &name)?.exists())
}

#[tauri::command]
async fn media_remove(dirs: State<'_, Dirs>, name: String) -> Result<(), String> {
    let path = media_path(&dirs, &name)?;
    if path.exists() {
        fs::remove_file(path).map_err(|e| e.to_string())?;
    }
    Ok(())
}

fn backup_path(path: &str) -> Result<PathBuf, String> {
    let p = PathBuf::from(path);
    match p.extension().and_then(|e| e.to_str()) {
        Some(ext) if ext.eq_ignore_ascii_case("cxbackup") => Ok(p),
        _ => Err("Backup files must use the .cxbackup extension".into()),
    }
}

#[tauri::command]
async fn backup_save(path: String, contents: String) -> Result<(), String> {
    let p = backup_path(&path)?;
    let tmp = p.with_extension("cxbackup.part");
    fs::write(&tmp, contents.as_bytes()).map_err(|e| e.to_string())?;
    fs::rename(&tmp, &p).map_err(|e| e.to_string())?;
    Ok(())
}

#[tauri::command]
async fn backup_read(path: String) -> Result<String, String> {
    let p = backup_path(&path)?;
    let meta = fs::metadata(&p).map_err(|e| e.to_string())?;
    if meta.len() > 512 * 1024 * 1024 {
        return Err("Backup file is too large".into());
    }
    fs::read_to_string(p).map_err(|e| e.to_string())
}

#[derive(serde::Serialize)]
struct AppInfo {
    device_name: String,
    data_dir: String,
    version: String,
}

#[tauri::command]
fn app_info(app: tauri::AppHandle) -> AppInfo {
    let device_name = std::env::var("COMPUTERNAME").unwrap_or_else(|_| "Windows PC".into());
    let data_dir = app
        .path()
        .app_data_dir()
        .map(|p| p.display().to_string())
        .unwrap_or_default();
    AppInfo {
        device_name,
        data_dir,
        version: app.package_info().version.to_string(),
    }
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .setup(|app| {
            // %APPDATA%\org.codexstocks.desktop - outside the install folder, so
            // upgrades and uninstalls (unless the owner opts in) keep the inventory.
            let data = app.path().app_data_dir()?;
            fs::create_dir_all(&data)?;
            let media = data.join("media");
            fs::create_dir_all(&media)?;
            let conn = Connection::open(data.join("codex-stocks.sqlite"))?;
            conn.execute_batch(
                "PRAGMA journal_mode = WAL; PRAGMA synchronous = FULL; PRAGMA busy_timeout = 5000; PRAGMA foreign_keys = OFF;",
            )?;
            app.manage(Db(Mutex::new(conn)));
            app.manage(Dirs { media });
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            db_execute,
            db_select,
            media_write,
            media_read,
            media_exists,
            media_remove,
            backup_save,
            backup_read,
            app_info
        ])
        .run(tauri::generate_context!())
        .expect("error while running CODE X STOCKS");
}
